package ctl

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
)

// schema.ts gives an app's or a workflow's code the tables and fields of
// its database as TypeScript types, so the SDK calls type-check against the
// metadata the project was last refreshed from.

type schemaCatalog struct {
	Databases []struct {
		Name   string        `json:"name"`
		Tables []schemaTable `json:"tables"`
	} `json:"databases"`
}

type schemaTable struct {
	Name        string        `json:"name"`
	DisplayName string        `json:"display_name"`
	Fields      []schemaField `json:"fields"`
}

type schemaField struct {
	Name          string   `json:"name"`
	Type          string   `json:"type"`
	ValueType     string   `json:"value_type"`
	Options       []string `json:"options"`
	Multiple      bool     `json:"multiple"`
	RelationTable string   `json:"relation_table"`
	Deleted       bool     `json:"deleted"`
}

// schema generates schema.ts for a project of the given kind ("app" or
// "workflow"), which names the command that refreshes it.
func (catalog schemaCatalog) schema(database, noun string) (string, error) {
	for _, candidate := range catalog.Databases {
		if candidate.Name == database {
			return generateSchema(noun, database, candidate.Tables), nil
		}
	}
	return "", fmt.Errorf("database %q not found (or not readable)", database)
}

// tsString quotes value as a TypeScript string literal.
func tsString(value string) string {
	var out bytes.Buffer
	encoder := json.NewEncoder(&out)
	encoder.SetEscapeHTML(false)
	_ = encoder.Encode(value)
	return strings.TrimSuffix(out.String(), "\n")
}

// tsComment makes text safe inside a /** */ comment on one line.
func tsComment(text string) string {
	text = strings.Join(strings.Fields(text), " ")
	return strings.ReplaceAll(text, "*/", "*\\/")
}

func storedTSType(storage string) string {
	switch storage {
	case "int", "float":
		return "number"
	case "string":
		return "string"
	}
	return "unknown"
}

// fieldTSType maps a field to the TypeScript type of its value (without
// null), a note for its doc comment, and whether the server computes it.
func fieldTSType(field schemaField) (string, string, bool) {
	switch field.Type {
	case "int", "float":
		return "number", "", false
	case "string":
		if len(field.Options) == 0 {
			return "string", "", false
		}
		if field.Multiple {
			return "string", "options, several joined by \",\" (see splitOptions): " + strings.Join(field.Options, ", "), false
		}
		literals := make([]string, 0, len(field.Options)+1)
		for _, option := range field.Options {
			literals = append(literals, tsString(option))
		}
		literals = append(literals, `""`)
		return strings.Join(literals, " | "), "", false
	case "formula":
		return storedTSType(field.ValueType), "formula, computed by the server (read-only)", true
	case "relation":
		return "number", "record id in table " + tsString(field.RelationTable), false
	case "file":
		return "number", "file id; files.url(id) downloads it", false
	}
	return "unknown", "field type " + tsString(field.Type), false
}

func generateSchema(noun, database string, tables []schemaTable) string {
	var out strings.Builder
	fmt.Fprintf(&out, "// Generated by autablectl from the metadata of database %s. Do not edit:\n", tsString(database))
	fmt.Fprintf(&out, "// run `autablectl %s sdk` again after tables or fields change.\n\n", noun)
	fmt.Fprintf(&out, "export const DATABASE = %s;\n\n", tsString(database))

	out.WriteString("/**\n * Field values of every table, keyed by table and field name. Fields the\n * caller may not read are missing from rows the server returns.\n */\n")
	if len(tables) == 0 {
		out.WriteString("export interface Tables {}\n\n")
	} else {
		out.WriteString("export interface Tables {\n")
	}
	readOnly := make([][]string, len(tables))
	for index, table := range tables {
		if table.DisplayName != "" && table.DisplayName != table.Name {
			fmt.Fprintf(&out, "  /** %s */\n", tsComment(table.DisplayName))
		}
		fmt.Fprintf(&out, "  %s: {\n", tsString(table.Name))
		for _, field := range table.Fields {
			if field.Deleted {
				continue
			}
			tsType, note, computed := fieldTSType(field)
			if note != "" {
				fmt.Fprintf(&out, "    /** %s */\n", tsComment(note))
			}
			fmt.Fprintf(&out, "    %s: %s | null;\n", tsString(field.Name), tsType)
			if computed {
				readOnly[index] = append(readOnly[index], tsString(field.Name))
			}
		}
		out.WriteString("  };\n")
	}
	if len(tables) > 0 {
		out.WriteString("}\n\n")
	}

	out.WriteString("/** Fields the server computes, per table; writes to them are rejected. */\n")
	if len(tables) == 0 {
		out.WriteString("export interface ReadOnlyFields {}\n\n")
	} else {
		out.WriteString("export interface ReadOnlyFields {\n")
		for index, table := range tables {
			fields := "never"
			if len(readOnly[index]) > 0 {
				fields = strings.Join(readOnly[index], " | ")
			}
			fmt.Fprintf(&out, "  %s: %s;\n", tsString(table.Name), fields)
		}
		out.WriteString("}\n\n")
	}

	names := make([]string, 0, len(tables))
	for _, table := range tables {
		names = append(names, tsString(table.Name))
	}
	fmt.Fprintf(&out, "export const TABLE_NAMES = [%s] as const;\n", strings.Join(names, ", "))
	return out.String()
}
